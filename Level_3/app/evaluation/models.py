from typing import List, Optional, Dict, Any, Union
from pydantic import BaseModel, Field


class MetricScore(BaseModel):
    """Detailed result for an individual DeepEval metric."""
    metric_name: str = Field(description="Name of the evaluated metric")
    score: float = Field(description="Score between 0.0 and 1.0")
    threshold: float = Field(description="Threshold required for passing")
    passed: bool = Field(description="Whether the score met or exceeded threshold")
    reason: Optional[str] = Field(default=None, description="Explanation or chain-of-thought justification")
    error: Optional[str] = Field(default=None, description="Error message if metric evaluation failed")
    score_breakdown: Optional[Dict[str, Any]] = Field(default=None, description="Sub-criteria score breakdown if available")


class RAGTestCaseInput(BaseModel):
    """Standardized input representation for evaluating a RAG generation."""
    input: str = Field(..., description="User query / prompt")
    actual_output: str = Field(..., description="The response generated by the RAG system / assistant")
    retrieval_context: List[str] = Field(..., description="Context chunks retrieved by the retriever")
    expected_output: Optional[str] = Field(default=None, description="Ground truth answer (from golden dataset)")
    context: Optional[List[str]] = Field(default=None, description="Optional ideal reference context")
    id: Optional[str] = Field(default=None, description="Unique identifier for the test case")
    metadata: Optional[Dict[str, Any]] = Field(default=None, description="Additional custom metadata")


class RAGEvaluationResult(BaseModel):
    """Evaluation output for a single RAG test case."""
    test_case_id: Optional[str] = None
    input: str
    actual_output: str
    expected_output: Optional[str] = None
    retrieval_context: List[str] = Field(default_factory=list)
    metrics: Dict[str, MetricScore] = Field(default_factory=dict, description="Results mapped by metric name")
    overall_passed: bool = Field(description="True if all evaluated metrics met their thresholds")
    average_score: float = Field(description="Average score across all successfully measured metrics")
    execution_time_seconds: float = Field(default=0.0)


class TurnEvaluationDetail(BaseModel):
    """Turn-level evaluation info inside a conversational session."""
    turn_index: int
    role: str
    content: str
    retrieval_context: Optional[List[str]] = None
    turn_metrics: Dict[str, MetricScore] = Field(default_factory=dict)


class ConversationalEvaluationResult(BaseModel):
    """Evaluation output for a multi-turn conversation session."""
    session_id: Optional[str] = None
    scenario: Optional[str] = None
    chatbot_role: Optional[str] = None
    total_turns: int = 0
    metrics: Dict[str, MetricScore] = Field(default_factory=dict, description="Session-level conversational metrics")
    turn_details: List[TurnEvaluationDetail] = Field(default_factory=list)
    overall_passed: bool = Field(description="True if all conversational metrics passed")
    average_score: float = Field(description="Average score across all session metrics")
    execution_time_seconds: float = Field(default=0.0)


class BatchEvaluationSummary(BaseModel):
    """Comprehensive summary report for a batch evaluation run (CI/CD or logging)."""
    run_id: str
    evaluation_type: str  # "RAG" or "Conversational"
    timestamp: str
    model_used: str
    total_test_cases: int
    passed_test_cases: int
    failed_test_cases: int
    pass_rate: float
    metric_averages: Dict[str, float]
    results: List[Union[RAGEvaluationResult, ConversationalEvaluationResult]]
    total_execution_time_seconds: float
